#!/usr/bin/env python3
"""Build single-file bundles for places that can't load several files (Claude artifacts, email, CodePen):
   dist/heydoc.bundle.css  = fonts + tokens + base + components + scene + HeyDoc logo class (data URI)
   dist/heydoc.bundle.js   = motion.js + brand.js
Run after any change to css/ or js/:  python3 scripts/bundle.py"""
import os, re, base64
R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rd = lambda p: open(os.path.join(R, p), encoding='utf-8').read()
ver = re.search(r'## \[(\d+\.\d+\.\d+)\]', rd('CHANGELOG.md')).group(1)
css = [f'/* HeyDoc Design System {ver} · single-file bundle (generated by scripts/bundle.py, do not edit) */',
       '@import url("https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600&family=Open+Sans:wght@300;400;600;700;800&display=swap");']
for f in ['css/tokens.css', 'css/base.css', 'css/components.css', 'css/scene.css']:
    css.append(f'/* ---- {f} ---- */\n' + re.sub(r'@import[^;]+;\s*', '', rd(f)))
logo = base64.b64encode(open(os.path.join(R, 'assets/logos/heydoc.webp'), 'rb').read()).decode()
css.append('/* ---- HeyDoc logo (colour, raster 900x542) · <span class="hd-brandmark" role="img" aria-label="HeyDoc AI"></span> ---- */\n'
           f'.hd-brandmark{{display:inline-block;height:48px;aspect-ratio:900/542;background:url(data:image/webp;base64,{logo}) center/contain no-repeat}}')
js = f'/* HeyDoc Design System {ver} · single-file bundle: motion.js + brand.js (generated, do not edit) */\n' + rd('js/motion.js') + '\n' + rd('js/brand.js')
os.makedirs(os.path.join(R, 'dist'), exist_ok=True)
open(os.path.join(R, 'dist/heydoc.bundle.css'), 'w', encoding='utf-8').write('\n'.join(css) + '\n')
open(os.path.join(R, 'dist/heydoc.bundle.js'), 'w', encoding='utf-8').write(js)
print(f'dist/ built for {ver}:', {f: os.path.getsize(os.path.join(R, 'dist', f)) for f in os.listdir(os.path.join(R, 'dist'))})
